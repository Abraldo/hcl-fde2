CREATE TABLE app_users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR2(320) NOT NULL,
    display_name VARCHAR2(120) NOT NULL,
    password_hash VARCHAR2(100) NOT NULL,
    role_name VARCHAR2(20) DEFAULT 'OPERATOR' NOT NULL,
    enabled NUMBER(1) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT app_users_email_uq UNIQUE (email),
    CONSTRAINT app_users_role_ck CHECK (role_name IN ('ADMIN', 'OPERATOR')),
    CONSTRAINT app_users_enabled_ck CHECK (enabled IN (0, 1))
);

CREATE TABLE app_config (
    config_id NUMBER PRIMARY KEY,
    temperature_threshold_c NUMBER(5, 2) DEFAULT 8 NOT NULL,
    minimum_duration_minutes NUMBER(5) DEFAULT 20 NOT NULL,
    maximum_gap_minutes NUMBER(5) DEFAULT 10 NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT app_config_singleton_ck CHECK (config_id = 1),
    CONSTRAINT app_config_threshold_ck CHECK (temperature_threshold_c BETWEEN -40 AND 40),
    CONSTRAINT app_config_duration_ck CHECK (minimum_duration_minutes BETWEEN 0 AND 1440),
    CONSTRAINT app_config_gap_ck CHECK (maximum_gap_minutes BETWEEN 1 AND 1440)
);

INSERT INTO app_config (config_id) VALUES (1);

CREATE TABLE bootstrap_guard (
    guard_id NUMBER PRIMARY KEY,
    CONSTRAINT bootstrap_guard_singleton_ck CHECK (guard_id = 1)
);

INSERT INTO bootstrap_guard (guard_id) VALUES (1);

CREATE TABLE sensor_readings (
    reading_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    truck_id VARCHAR2(40) NOT NULL,
    reading_time TIMESTAMP WITH TIME ZONE NOT NULL,
    temperature_c NUMBER(7, 3) NOT NULL,
    humidity_pct NUMBER(6, 3) NOT NULL,
    imported_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT sensor_readings_truck_time_uq UNIQUE (truck_id, reading_time),
    CONSTRAINT sensor_readings_humidity_ck CHECK (humidity_pct BETWEEN 0 AND 100)
);

CREATE INDEX sensor_readings_time_ix ON sensor_readings (reading_time);

CREATE OR REPLACE PACKAGE cold_chain_store AS
    PROCEDURE save_config(
        p_temperature_threshold_c IN NUMBER,
        p_minimum_duration_minutes IN NUMBER,
        p_maximum_gap_minutes IN NUMBER
    );
    PROCEDURE add_reading(
        p_truck_id IN VARCHAR2,
        p_reading_time IN TIMESTAMP WITH TIME ZONE,
        p_temperature_c IN NUMBER,
        p_humidity_pct IN NUMBER
    );
END cold_chain_store;
/

CREATE OR REPLACE PACKAGE BODY cold_chain_store AS
    PROCEDURE save_config(
        p_temperature_threshold_c IN NUMBER,
        p_minimum_duration_minutes IN NUMBER,
        p_maximum_gap_minutes IN NUMBER
    ) IS
    BEGIN
        UPDATE app_config
           SET temperature_threshold_c = p_temperature_threshold_c,
               minimum_duration_minutes = p_minimum_duration_minutes,
               maximum_gap_minutes = p_maximum_gap_minutes,
               updated_at = SYSTIMESTAMP
         WHERE config_id = 1;
        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20001, 'Alert configuration row is missing');
        END IF;
    END save_config;

    PROCEDURE add_reading(
        p_truck_id IN VARCHAR2,
        p_reading_time IN TIMESTAMP WITH TIME ZONE,
        p_temperature_c IN NUMBER,
        p_humidity_pct IN NUMBER
    ) IS
    BEGIN
        INSERT INTO sensor_readings (truck_id, reading_time, temperature_c, humidity_pct)
        VALUES (p_truck_id, p_reading_time, p_temperature_c, p_humidity_pct);
    END add_reading;
END cold_chain_store;
